export function useI18n() {
  const locale = useState<LocaleCode>('locale', () => {
    if (import.meta.client) {
      const saved = localStorage.getItem('reelkit_locale') as LocaleCode | null
      if (saved && messages[saved]) return saved
    }
    return 'en'
  })

  const t = (key: string) => messages[locale.value]?.[key] || messages.en[key] || key

  function setLocale(code: LocaleCode) {
    locale.value = code
    if (import.meta.client) localStorage.setItem('reelkit_locale', code)
  }

  return { locale, t, setLocale, LOCALES }
}
